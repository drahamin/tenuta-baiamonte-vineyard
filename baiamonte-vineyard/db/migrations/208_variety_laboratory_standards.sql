CREATE TABLE IF NOT EXISTS variety_lab_standards (
  id CHAR(36) PRIMARY KEY,
  estate_id CHAR(36) NOT NULL,
  variety_id CHAR(36) NOT NULL,
  sample_type ENUM('grape','must','wine') NOT NULL,
  process_stage VARCHAR(100) NOT NULL,
  analyte_code VARCHAR(80) NOT NULL,
  analyte_name VARCHAR(160) NOT NULL,
  unit VARCHAR(50) NOT NULL,
  target_min DECIMAL(16,6) NULL,
  target_max DECIMAL(16,6) NULL,
  source_reference VARCHAR(700) NOT NULL,
  notes TEXT NULL,
  approved_by VARCHAR(180) NOT NULL,
  approved_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_variety_lab_standard (estate_id,variety_id,sample_type,process_stage,analyte_code,unit),
  KEY ix_variety_lab_standard_match (estate_id,active,variety_id,sample_type,process_stage,analyte_code,unit),
  CONSTRAINT fk_variety_lab_standard_estate FOREIGN KEY (estate_id) REFERENCES estates(id) ON DELETE CASCADE,
  CONSTRAINT fk_variety_lab_standard_variety FOREIGN KEY (variety_id) REFERENCES grape_varieties(id) ON DELETE CASCADE,
  CONSTRAINT ck_variety_lab_standard_bounds CHECK (target_min IS NOT NULL OR target_max IS NOT NULL),
  CONSTRAINT ck_variety_lab_standard_order CHECK (target_min IS NULL OR target_max IS NULL OR target_min<=target_max)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
